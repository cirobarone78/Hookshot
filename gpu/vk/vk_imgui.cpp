// ---- the game's own menu font, from the player's game files, in memory (vk_game_font.h) ----
/// The game's romfs folder: the one the game runs from (--romfs, or romfs beside the executable: host/hos_main.c)
std::string romfs_dir() {
    if (host && host->romfs_dir)
        if (const char* d = host->romfs_dir(); d && *d) return d;
    return "";
}
ImFont* game_font(const char* name) {
    static game_font::Reader reader;
    static bool opened = false, open = false;
    if (!opened) opened = true, open = reader.open(romfs_dir());
    if (!open) return nullptr;
    std::vector<unsigned char> bytes = reader.read(name);
    if (bytes.empty()) return nullptr;
    void* font = IM_ALLOC(bytes.size());   // (the atlas owns it: in memory only)
    memcpy(font, bytes.data(), bytes.size());
    ImFontConfig cfg;
    snprintf(cfg.Name, sizeof cfg.Name, "%s", name);
    return ImGui::GetIO().Fonts->AddFontFromMemoryTTF(font, (int)bytes.size(), 18.0f, &cfg);
}
ImFont* bundled_font(const unsigned char* data, unsigned size, const char* name) {
    ImFontConfig cfg;
    cfg.FontDataOwnedByAtlas = false;   // (the compiled-in bytes)
    snprintf(cfg.Name, sizeof cfg.Name, "%s", name);
    return ImGui::GetIO().Fonts->AddFontFromMemoryTTF((void*)data, (int)size, 18.0f, &cfg);
}
i18n::Lang active_ui_lang() {
    if (!i18n::state_ready().load(std::memory_order_acquire)) {
        char exe[MAX_PATH];
        const DWORD n = game_module_path(exe, MAX_PATH);
        std::string dir(exe, n);
        const size_t slash = dir.find_last_of("\\/");
        dir = slash == std::string::npos ? std::string() : dir.substr(0, slash + 1);
        i18n::init(dir.empty() ? nullptr : dir.c_str());
    }
    return i18n::current_lang();
}
bool valid_sfnt_or_ttc(const std::vector<unsigned char>& bytes, int want_face, int* out_face) {
    if (bytes.size() < 12) return false;
    const unsigned char* p = bytes.data();
    const uint32_t tag = ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) | ((uint32_t)p[2] << 8) | (uint32_t)p[3];
    if (tag == 0x74746366u) {   // "ttcf"
        const uint32_t n = ((uint32_t)p[8] << 24) | ((uint32_t)p[9] << 16) | ((uint32_t)p[10] << 8) | (uint32_t)p[11];
        if (!n) return false;
        *out_face = want_face >= 0 && (uint32_t)want_face < n ? want_face : 0;
        return true;
    }
    if (tag == 0x00010000u || tag == 0x4F54544Fu || tag == 0x74727565u) {   // TTF / OTF ("OTTO") / "true"
        *out_face = 0;
        return true;
    }
    return false;
}
struct FallbackFontBlob {
    std::vector<unsigned char> bytes;
    int face = 0;
    std::string label;
};
bool try_read_font_file(const char* path, int want_face, FallbackFontBlob* out) {
    if (!path || !*path) return false;
    FILE* f = fopen(path, "rb");
    if (!f) return false;
    std::vector<unsigned char> data;
    if (fseek(f, 0, SEEK_END) == 0) {
        const long sz = ftell(f);
        if (sz > 12 && sz < 64 * 1024 * 1024 && fseek(f, 0, SEEK_SET) == 0) {
            data.resize((size_t)sz);
            if (fread(data.data(), 1, data.size(), f) != data.size()) data.clear();
        }
    }
    fclose(f);
    int face = 0;
    if (!valid_sfnt_or_ttc(data, want_face, &face)) return false;
    out->bytes = std::move(data);
    out->face = face;
    out->label = path;
    return true;
}
const FallbackFontBlob* cjk_fallback_font(i18n::Lang l, bool bold) {
    static FallbackFontBlob regular_blob, bold_blob;
    static i18n::Lang cached_reg = i18n::kLangCount, cached_bold = i18n::kLangCount;
    FallbackFontBlob& dst = bold ? bold_blob : regular_blob;
    i18n::Lang& cached = bold ? cached_bold : cached_reg;
    if (cached == l) return dst.bytes.empty() ? nullptr : &dst;
    cached = l;
    dst.bytes.clear();
    if (const char* env = getenv("RX_VK_UI_FONT"); env && *env && try_read_font_file(env, 0, &dst)) return &dst;
#ifdef _WIN32
    std::string dir = "C:/Windows/Fonts/";
    if (const char* wd = getenv("WINDIR"); wd && *wd) {
        dir = wd;
        if (dir.back() != '/' && dir.back() != '\\') dir += '/';
        dir += "Fonts/";
    }
    struct Cand { const char* file; int face; };
    std::vector<Cand> cands;
    if (l == i18n::kJa) {
        if (bold) cands = {{"YuGothB.ttc", 0}, {"YuGothM.ttc", 0}, {"meiryob.ttc", 0}, {"meiryo.ttc", 0}, {"msgothic.ttc", 0}};
        else cands = {{"YuGothM.ttc", 0}, {"YuGothR.ttc", 0}, {"meiryo.ttc", 0}, {"msgothic.ttc", 0}};
    } else if (l == i18n::kKo) {
        if (bold) cands = {{"malgunbd.ttf", 0}, {"malgun.ttf", 0}};
        else cands = {{"malgun.ttf", 0}};
    } else if (l == i18n::kZhHans) {
        if (bold) cands = {{"msyhbd.ttc", 0}, {"msyh.ttc", 0}, {"simhei.ttf", 0}, {"simsun.ttc", 0}};
        else cands = {{"msyh.ttc", 0}, {"simsun.ttc", 0}, {"simhei.ttf", 0}};
    } else if (l == i18n::kZhHant) {
        if (bold) cands = {{"msjhbd.ttc", 0}, {"msjh.ttc", 0}, {"mingliu.ttc", 0}};
        else cands = {{"msjh.ttc", 0}, {"mingliu.ttc", 0}};
    }
    for (const Cand& c : cands) {
        if (try_read_font_file((dir + c.file).c_str(), c.face, &dst)) return &dst;
    }
#else
    const int noto_face = l == i18n::kJa ? 0 : l == i18n::kKo ? 1 : l == i18n::kZhHans ? 2 : 3;
    const char* const noto_paths[] = {
        bold ? "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc" : "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
        bold ? "/usr/share/fonts/noto/NotoSansCJK-Bold.ttc" : "/usr/share/fonts/noto/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/google-noto-cjk/NotoSansCJK-Regular.ttc",
    };
    for (const char* p : noto_paths)
        if (try_read_font_file(p, noto_face, &dst)) return &dst;
    const char* extra_paths[4] = {};
    if (l == i18n::kJa) {
        extra_paths[0] = "/usr/share/fonts/truetype/takao-gothic/TakaoPGothic.ttf";
        extra_paths[1] = "/usr/share/fonts/truetype/fonts-japanese-gothic.ttf";
    } else if (l == i18n::kKo) {
        extra_paths[0] = "/usr/share/fonts/truetype/nanum/NanumGothic.ttf";
    } else {
        extra_paths[0] = "/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc";
        extra_paths[1] = "/usr/share/fonts/truetype/wqy/wqy-microhei.ttf";
    }
    for (const char* p : extra_paths)
        if (p && try_read_font_file(p, 0, &dst)) return &dst;
    const char* const fc_cmd = l == i18n::kJa       ? (bold ? "fc-match -f '%{file}\n%{index}\n' ':lang=ja:weight=bold' 2>/dev/null"
                                                             : "fc-match -f '%{file}\n%{index}\n' ':lang=ja' 2>/dev/null")
                               : l == i18n::kKo     ? (bold ? "fc-match -f '%{file}\n%{index}\n' ':lang=ko:weight=bold' 2>/dev/null"
                                                             : "fc-match -f '%{file}\n%{index}\n' ':lang=ko' 2>/dev/null")
                               : l == i18n::kZhHans ? (bold ? "fc-match -f '%{file}\n%{index}\n' ':lang=zh-cn:weight=bold' 2>/dev/null"
                                                             : "fc-match -f '%{file}\n%{index}\n' ':lang=zh-cn' 2>/dev/null")
                                                    : (bold ? "fc-match -f '%{file}\n%{index}\n' ':lang=zh-tw:weight=bold' 2>/dev/null"
                                                             : "fc-match -f '%{file}\n%{index}\n' ':lang=zh-tw' 2>/dev/null");
    if (FILE* fp = popen(fc_cmd, "r")) {
        char path_buf[512] = {}, idx_buf[32] = {};
        const bool got_path = fgets(path_buf, sizeof path_buf, fp) != nullptr;
        const bool got_idx = got_path && fgets(idx_buf, sizeof idx_buf, fp) != nullptr;
        pclose(fp);
        if (got_path) {
            size_t len = strlen(path_buf);
            while (len > 0 && (path_buf[len - 1] == '\n' || path_buf[len - 1] == '\r')) path_buf[--len] = 0;
            const int fc_idx = got_idx ? atoi(idx_buf) : 0;
            if (len > 0 && try_read_font_file(path_buf, fc_idx, &dst)) return &dst;
        }
    }
#endif
    return nullptr;
}
void merge_memory_font(ImFont* dst, const void* data, int size, int face, const char* name) {
    if (!dst || !data || size <= 0) return;
    ImFontConfig cfg;
    cfg.MergeMode = true;
    cfg.DstFont = dst;
    cfg.FontDataOwnedByAtlas = false;
    cfg.FontNo = face;
    snprintf(cfg.Name, sizeof cfg.Name, "%s", name);
    ImGui::GetIO().Fonts->AddFontFromMemoryTTF((void*)data, size, 0.0f, &cfg);
}
void merge_language_fallbacks(ImFont* body, ImFont* strong, ImFont* heading) {
    const i18n::Lang l = active_ui_lang();
    const uint32_t probe = i18n::script_probe_char(l);
    if (!probe) return;
    const ImWchar wp = (ImWchar)probe;
    auto needs = [&](ImFont* f) { return f && !f->IsGlyphInFont(wp); };
    if (!i18n::is_cjk(l)) {
        if (needs(body)) merge_memory_font(body, hookshot_font_body, (int)hookshot_font_body_size, 0, "Libertinus Sans Fallback");
        if (needs(strong)) merge_memory_font(strong, hookshot_font_strong, (int)hookshot_font_strong_size, 0, "Libertinus Strong Fallback");
        if (needs(heading)) merge_memory_font(heading, hookshot_font_heading, (int)hookshot_font_heading_size, 0, "Libertinus Heading Fallback");
    } else if (needs(body) || needs(strong) || needs(heading)) {
        const FallbackFontBlob* reg = cjk_fallback_font(l, false);
        const FallbackFontBlob* bld = cjk_fallback_font(l, true);
        const FallbackFontBlob* b_src = reg ? reg : bld;
        const FallbackFontBlob* s_src = bld ? bld : reg;
        if (b_src && needs(body)) merge_memory_font(body, b_src->bytes.data(), (int)b_src->bytes.size(), b_src->face, "CJK UI Body");
        if (s_src && needs(strong)) merge_memory_font(strong, s_src->bytes.data(), (int)s_src->bytes.size(), s_src->face, "CJK UI Strong");
        if (s_src && needs(heading)) merge_memory_font(heading, s_src->bytes.data(), (int)s_src->bytes.size(), s_src->face, "CJK UI Heading");
        if (b_src || s_src)
            logf("vk: ui: merged CJK fallback font (%s) for %s", (b_src ? b_src : s_src)->label.c_str(), i18n::lang_code(l));
    }
    if (needs(body) || needs(strong) || needs(heading)) {
        i18n::set_active_lang(i18n::kEnUS);
        logf("vk: ui: no font covers %s (U+%04X), falling back UI to English (set RX_VK_UI_FONT to a TTF/TTC path)", i18n::lang_code(l),
             (unsigned)probe);
    }
}
/// The fonts: the game's own when its files have them (all three or none, so the menu never mixes the two), else Libertinus
void load_fonts() {
    const char* off = getenv("RX_VK_UI_GAME_FONT");   // (0: Libertinus whatever the game's files have)
    ImFont* body = nullptr;
    ImFont* strong = nullptr;
    ImFont* heading = nullptr;
    if (!(off && *off == '0')) {
        body = game_font("ClarimoUDPE-Regular");
        strong = body ? game_font("ClarimoUDPE-DemiBold") : nullptr;
        heading = strong ? game_font("CetraDisplayPro-Medium") : nullptr;
    }
    if (body && strong && heading) {
        logf("vk: ui: the game's own menu font, from its files");
    } else {
        ImGui::GetIO().Fonts->Clear();
        body = bundled_font(hookshot_font_body, hookshot_font_body_size, "Libertinus Sans");
        strong = bundled_font(hookshot_font_strong, hookshot_font_strong_size, "Libertinus Sans Bold");
        heading = bundled_font(hookshot_font_heading, hookshot_font_heading_size, "Libertinus Serif Semibold");
        logf("vk: ui: the bundled font (Libertinus): the game's files have no menu font");
    }
    merge_language_fallbacks(body, strong, heading);
    fonts_ = {body, strong, heading};
}

// ---- textures: made and updated on the present's command buffer, let go some frames later ----
struct Tex {
    VkImage image = VK_NULL_HANDLE;
    VmaAllocation alloc = nullptr;
    VkImageView view = VK_NULL_HANDLE;
    VkDescriptorSet set = VK_NULL_HANDLE;
};
struct Dead {   // (no longer used by anything recorded after `at`: gone once the frames in flight then are done)
    int64_t at;
    Tex tex;
    VkBuffer buf = VK_NULL_HANDLE;
    VmaAllocation buf_alloc = nullptr;
};
std::vector<Dead> dead;
constexpr int64_t kFramesLater = 4;   // (present_image keeps three frames in flight)
void reap(bool all) {
    for (size_t i = 0; i < dead.size();) {
        Dead& d = dead[i];
        if (!all && presents - d.at < kFramesLater) { i++; continue; }
        if (d.tex.set) ImGui_ImplVulkan_RemoveTexture(d.tex.set);
        if (d.tex.view) vkDestroyImageView(dev.device, d.tex.view, nullptr);
        if (d.tex.image) destroy_image(d.tex.image, d.tex.alloc);
        if (d.buf) destroy_buffer(d.buf, d.buf_alloc);
        dead[i] = dead.back();
        dead.pop_back();
    }
}
/// The format the overlays draw into: the window images' views, or headless the shots' RGBA (vk_replay.cpp RX_VK_SHOT_MENU)
VkFormat target_format() { return dev.offscreen ? VK_FORMAT_R8G8B8A8_UNORM : dev.swap_view_format; }
bool is_srgb(VkFormat f) {
    return f == VK_FORMAT_B8G8R8A8_SRGB || f == VK_FORMAT_R8G8B8A8_SRGB || f == VK_FORMAT_A8B8G8R8_SRGB_PACK32;
}
/// The draw lists' colours (sRGB, as vk_ui.h gives them) in linear light, for an sRGB window image that encodes them again
void linearize(ImDrawData* dd) {
    static unsigned char lut[256];
    if (!lut[255])
        for (int i = 0; i < 256; i++) {
            const float c = i / 255.0f, l = c <= 0.04045f ? c / 12.92f : std::pow((c + 0.055f) / 1.055f, 2.4f);
            lut[i] = (unsigned char)(l * 255.0f + 0.5f);
        }
    for (ImDrawList* list : dd->CmdLists)
        for (ImDrawVert& v : list->VtxBuffer)
            v.col = (v.col & IM_COL32_A_MASK) | (ImU32)lut[v.col >> IM_COL32_R_SHIFT & 0xFF] << IM_COL32_R_SHIFT |
                    (ImU32)lut[v.col >> IM_COL32_G_SHIFT & 0xFF] << IM_COL32_G_SHIFT | (ImU32)lut[v.col >> IM_COL32_B_SHIFT & 0xFF] << IM_COL32_B_SHIFT;
}
/// (an HDR10 window image: ST 2084 (PQ) code values in Rec. 2020, framegen_hdr's) an sRGB colour as HDR10 shows it at the
/// paper white of the Insert menu's HDR rows: decoded, its primaries to Rec. 2020, its white at paper white nits, PQ coded
ImU32 hdr10_of(ImU32 c, float white) {
    static float lin[256];
    static unsigned char pq[4097];
    static float pq_white = -1;
    if (pq_white != white) {
        pq_white = white;
        for (int i = 0; i < 256; i++) {
            const float v = i / 255.0f;
            lin[i] = v <= 0.04045f ? v / 12.92f : std::pow((v + 0.055f) / 1.055f, 2.4f);
        }
        for (int i = 0; i <= 4096; i++) {   // (linear light, 1 the paper white, to the 8-bit PQ code)
            const float y = std::pow(i / 4096.0f * white / 10000.0f, 0.1593017578125f);
            const float e = std::pow((0.8359375f + 18.8515625f * y) / (1 + 18.6875f * y), 78.84375f);
            pq[i] = (unsigned char)std::clamp((int)(e * 255.0f + 0.5f), 0, 255);
        }
    }
    const float r = lin[c >> IM_COL32_R_SHIFT & 0xFF], g = lin[c >> IM_COL32_G_SHIFT & 0xFF], b = lin[c >> IM_COL32_B_SHIFT & 0xFF];
    auto code = [&](float v) { return (ImU32)pq[std::clamp((int)(v * 4096.0f + 0.5f), 0, 4096)]; };
    return (c & IM_COL32_A_MASK) | code(0.6274f * r + 0.3293f * g + 0.0433f * b) << IM_COL32_R_SHIFT |
           code(0.0691f * r + 0.9195f * g + 0.0114f * b) << IM_COL32_G_SHIFT | code(0.0164f * r + 0.0880f * g + 0.8956f * b) << IM_COL32_B_SHIFT;
}
void hdr10(ImDrawData* dd) {
    const float white = (float)std::clamp(opts.hdr_white, 80, 400);
    for (ImDrawList* list : dd->CmdLists)
        for (ImDrawVert& v : list->VtxBuffer) v.col = hdr10_of(v.col, white);
}
void layout(VkCommandBuffer cmd, VkImage image, VkImageLayout from, VkImageLayout to, VkPipelineStageFlags2 src_stage,
            VkAccessFlags2 src, VkPipelineStageFlags2 dst_stage, VkAccessFlags2 dst) {
    VkImageMemoryBarrier2 b{VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER_2};
    b.srcStageMask = src_stage, b.srcAccessMask = src;
    b.dstStageMask = dst_stage, b.dstAccessMask = dst;
    b.oldLayout = from, b.newLayout = to;
    b.srcQueueFamilyIndex = b.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    b.image = image;
    b.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
    VkDependencyInfo d{VK_STRUCTURE_TYPE_DEPENDENCY_INFO};
    d.imageMemoryBarrierCount = 1, d.pImageMemoryBarriers = &b;
    vkCmdPipelineBarrier2(cmd, &d);
}
/// tex's pixels in rect (x, y, w, h), as RGBA, into dst
void pixels(ImTextureData* tex, int x, int y, int w, int h, unsigned char* dst) {
    for (int row = 0; row < h; row++) {
        const unsigned char* src = (const unsigned char*)tex->GetPixelsAt(x, y + row);
        if (tex->Format == ImTextureFormat_RGBA32 && dev.hdr && tex != ImGui::GetIO().Fonts->TexData) {   // (the logo, as HDR10 shows it)
            const float white = (float)std::clamp(opts.hdr_white, 80, 400);
            for (int i = 0; i < w; i++) {
                ImU32 c;
                memcpy(&c, src + i * 4, 4);
                c = hdr10_of(c, white);
                memcpy(dst + ((size_t)row * w + i) * 4, &c, 4);
            }
        } else if (tex->Format == ImTextureFormat_RGBA32) {   // (the glyphs: white, their coverage in alpha, the same in any space)
            memcpy(dst + (size_t)row * w * 4, src, (size_t)w * 4);
        } else {   // (Alpha8: white, its coverage as alpha)
            for (int i = 0; i < w; i++) {
                unsigned char* p = dst + ((size_t)row * w + i) * 4;
                p[0] = p[1] = p[2] = 255, p[3] = src[i];
            }
        }
    }
}
void update_texture(VkCommandBuffer cmd, ImTextureData* tex) {
    if (tex->Status == ImTextureStatus_WantDestroy) {
        if (Tex* t = (Tex*)tex->BackendUserData) dead.push_back({presents, *t}), IM_DELETE(t);
        tex->SetTexID(ImTextureID_Invalid);
        tex->BackendUserData = nullptr;
        tex->SetStatus(ImTextureStatus_Destroyed);
        return;
    }
    const bool create = tex->Status == ImTextureStatus_WantCreate;
    if (!create && !tex->BackendUserData) return;
    // (what to copy: all of it when new, else the updates queued)
    ImVector<ImTextureRect> rects;
    if (create) rects.push_back({0, 0, (unsigned short)tex->Width, (unsigned short)tex->Height});
    else rects = tex->Updates;
    if (rects.empty()) rects.push_back(tex->UpdateRect);
    uint64_t size = 0;
    for (const ImTextureRect& r : rects) size += (uint64_t)r.w * r.h * 4;
    // (the staging buffer first, then the image: a failure leaves nothing behind, and the texture is asked for again)
    VkBuffer buf = VK_NULL_HANDLE;
    VmaAllocation buf_alloc = nullptr;
    void* map = nullptr;
    if (!size || !create_buffer(size, VK_BUFFER_USAGE_TRANSFER_SRC_BIT, true, buf, buf_alloc, &map)) return;
    if (create) {
        Tex made;
        VkImageCreateInfo ci{VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO};
        ci.imageType = VK_IMAGE_TYPE_2D;
        // (an sRGB window image without a UNORM view blends in linear light: the logo sampled as sRGB to match, vk_ui.h's
        // colours made linear in record. The glyphs are white, their coverage in alpha: the same either way)
        ci.format = srgb_target ? VK_FORMAT_R8G8B8A8_SRGB : VK_FORMAT_R8G8B8A8_UNORM;
        ci.extent = {(uint32_t)tex->Width, (uint32_t)tex->Height, 1};
        ci.mipLevels = ci.arrayLayers = 1;
        ci.samples = VK_SAMPLE_COUNT_1_BIT;
        ci.tiling = VK_IMAGE_TILING_OPTIMAL;
        ci.usage = VK_IMAGE_USAGE_SAMPLED_BIT | VK_IMAGE_USAGE_TRANSFER_DST_BIT;
        ci.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
        bool ok = create_image(ci, made.image, made.alloc);
        if (ok) {
            VkImageViewCreateInfo vi{VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
            vi.image = made.image;
            vi.viewType = VK_IMAGE_VIEW_TYPE_2D;
            vi.format = ci.format;
            vi.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
            ok = vkCreateImageView(dev.device, &vi, nullptr, &made.view) == VK_SUCCESS;
        }
        if (ok) ok = (made.set = ImGui_ImplVulkan_AddTexture(made.view, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL)) != VK_NULL_HANDLE;
        if (!ok) {   // (nothing recorded uses them yet)
            if (made.view) vkDestroyImageView(dev.device, made.view, nullptr);
            if (made.image) destroy_image(made.image, made.alloc);
            destroy_buffer(buf, buf_alloc);
            return;
        }
        Tex* t = IM_NEW(Tex)();
        *t = made;
        tex->BackendUserData = t;
        tex->SetTexID((ImTextureID)t->set);
    }
    Tex* t = (Tex*)tex->BackendUserData;
    std::vector<VkBufferImageCopy> copies;
    uint64_t at = 0;
    for (const ImTextureRect& r : rects) {
        pixels(tex, r.x, r.y, r.w, r.h, (unsigned char*)map + at);
        VkBufferImageCopy c{};
        c.bufferOffset = at;
        c.imageSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
        c.imageOffset = {r.x, r.y, 0};
        c.imageExtent = {r.w, r.h, 1};
        copies.push_back(c);
        at += (uint64_t)r.w * r.h * 4;
    }
    // Sequential-write host memory need not be coherent; publish every packed rectangle before GPU use.
    flush_mapped(buf_alloc, at);
    layout(cmd, t->image, create ? VK_IMAGE_LAYOUT_UNDEFINED : VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL,
           VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT, 0, VK_PIPELINE_STAGE_2_COPY_BIT,
           VK_ACCESS_2_TRANSFER_WRITE_BIT);
    vkCmdCopyBufferToImage(cmd, buf, t->image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, (uint32_t)copies.size(), copies.data());
    layout(cmd, t->image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL, VK_PIPELINE_STAGE_2_COPY_BIT,
           VK_ACCESS_2_TRANSFER_WRITE_BIT, VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT, VK_ACCESS_2_SHADER_SAMPLED_READ_BIT);
    dead.push_back({presents, Tex{}, buf, buf_alloc});   // (the staging buffer: let go once this frame is done)
    tex->SetStatus(ImTextureStatus_OK);
}

bool init() {
    tried = true;
    if (!dev.device || (!dev.offscreen && (dev.swap_views.empty() || !dev.swap_views[0]))) {
        logf("vk: ui: no views of the window's images (the surface does not allow drawing into them): no menu or counter");
        return false;
    }
    IMGUI_CHECKVERSION();
    ImGui::CreateContext();
    ImGuiIO& io = ImGui::GetIO();
    io.IniFilename = nullptr;
    io.LogFilename = nullptr;
    io.Fonts->TexDesiredFormat = ImTextureFormat_RGBA32;
    if (!ImGui_ImplVulkan_LoadFunctions(VK_API_VERSION_1_3, load)) {
        logf("vk: ui: the Vulkan functions did not load");
        return false;
    }
    pipeline_format = target_format();
    srgb_target = is_srgb(pipeline_format);
    ImGui_ImplVulkan_InitInfo ii{};
    ii.ApiVersion = VK_API_VERSION_1_3;
    ii.Instance = dev.instance;
    ii.PhysicalDevice = dev.physical;
    ii.Device = dev.device;
    ii.QueueFamily = dev.queue_family;
    ii.Queue = dev.queue;   // (for the backend's own uploads, never used here: update_texture)
    ii.DescriptorPoolSize = 16;   // (the backend's own pool: the textures' descriptor sets)
    ii.MinImageCount = 2;
    ii.ImageCount = 4;            // (its vertex buffers in turn: one more than the three frames present_image keeps in flight)
    ii.UseDynamicRendering = true;
    ii.PipelineInfoMain.PipelineRenderingCreateInfo.sType = VK_STRUCTURE_TYPE_PIPELINE_RENDERING_CREATE_INFO;
    ii.PipelineInfoMain.PipelineRenderingCreateInfo.colorAttachmentCount = 1;
    ii.PipelineInfoMain.PipelineRenderingCreateInfo.pColorAttachmentFormats = &pipeline_format;
    if (!ImGui_ImplVulkan_Init(&ii)) {
        logf("vk: ui: the Vulkan backend did not start");
        return false;
    }
    load_fonts();
#ifdef HOOKSHOT_LOGO
    logo_ = IM_NEW(ImTextureData)();
    logo_->Create(ImTextureFormat_RGBA32, (int)hookshot_logo_w, (int)hookshot_logo_h);
    memcpy(logo_->GetPixels(), hookshot_logo_rgba, (size_t)hookshot_logo_w * hookshot_logo_h * 4);
    logo_->UseColors = true;
    ImGui::RegisterUserTexture(logo_);
    logo_aspect = (float)hookshot_logo_w / hookshot_logo_h;
#endif
    logf("vk: ui: Dear ImGui %s on the window's images (format %d%s)", IMGUI_VERSION, (int)pipeline_format,
         srgb_target ? ", sRGB: colours made linear" : "");
    return true;
}

std::vector<std::pair<ImFont*, float>> to_bake, kept;
std::vector<float> baked_sizes;
std::vector<ImWchar> prebake_extra;
size_t prebake_pos = 0;
void bake_some() {
    if (prebake_extra.empty()) {
        for (int k = 0; k < 4 && !to_bake.empty(); k++) {   // (a few a frame: each is ~95 ASCII glyphs rasterized)
            ImFontBaked* b = to_bake.back().first->GetFontBaked(to_bake.back().second);
            for (ImWchar c = 32; c < 127; c++) b->FindGlyph(c);
            to_bake.pop_back();
        }
    } else if (!to_bake.empty()) {   // (spread non-ASCII/CJK glyphs across frames so startup/gameplay stays smooth)
        constexpr size_t kExtraPerFrame = 48;
        ImFontBaked* b = to_bake.back().first->GetFontBaked(to_bake.back().second);
        if (prebake_pos == 0) {
            for (ImWchar c = 32; c < 127; c++) b->FindGlyph(c);
        }
        const size_t end = std::min(prebake_extra.size(), prebake_pos + kExtraPerFrame);
        for (size_t i = prebake_pos; i < end; i++) b->FindGlyph(prebake_extra[i]);
        prebake_pos = end;
        if (prebake_pos >= prebake_extra.size()) {
            prebake_pos = 0;
            to_bake.pop_back();
        }
    }
    // (the sizes baked ahead marked used each frame: ImGui lets go of sizes unused for two frames when its atlas needs room,
    // and would bake them all again on the menu's first open)
    for (const auto& [font, px] : kept) font->GetFontBaked(px);
}

